#!/usr/bin/env node
/**
 * scripts/build-client-indexes.mjs — Branduri-500 v16 (D-2026-09-26).
 *
 * Why: the Header, Footer and contact page are client components present on
 * every page. They used to import src/data/allBrandsIndex.js (directly or via
 * siteStats.js), which imports brandContent.js and its ~160 batch files, so
 * ~12 MB of brand-content source ended up in the JavaScript every visitor
 * downloads (PageSpeed mobile, /pompe-industriale, 26.09: 3.5 MB transferred,
 * TBT 910 ms). Client components now import only the compact, generated
 * files below; the full index stays on the server.
 *
 * Writes:
 *   src/data/headerMenus.js        HEADER_CATEGORY_MENUS (the v11 dropdowns:
 *                                  6 product types, 10 top brands, brand
 *                                  count), CLIENT_CATEGORIES [{slug,name}],
 *                                  CLIENT_BRAND_STATS {total, indexed,
 *                                  withContent} (siteStats.js). Small; every
 *                                  page loads it.
 *   src/data/headerSearchIndex.js  HEADER_SEARCH_INDEX (categories, product
 *                                  types, brands). Imported lazily by the
 *                                  Header on the first search keystroke.
 *   src/data/brandCategorySlugs.js BRAND_CATEGORY_SLUGS {simpleSlug: [slug…]}
 *                                  (contact form pre-ticking only).
 *
 * Deterministic, zero tokens:
 *   node scripts/build-client-indexes.mjs          # write
 *   node scripts/build-client-indexes.mjs --check  # exit 1 if stale
 *
 * Run it after anything that changes brands or categories (the same moments
 * build-llms.mjs is run). G19 runs the --check comparison too.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { importDataFile } from './gates/_lib/loader.mjs';

const ROOT_DEFAULT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const HEADER = (what) => `// GENERATED by scripts/build-client-indexes.mjs — do not edit by hand.
// ${what}
// Client-safe: no imports. Regenerate after any brand/category change:
//   node scripts/build-client-indexes.mjs
`;

export async function buildClientIndexes(root = ROOT_DEFAULT) {
  const idx = await importDataFile(root, 'allBrandsIndex.js');
  const products = await importDataFile(root, 'products.js');
  const categories = idx.allCategoriesUnified;

  // Search index — same entries and matching fields as the pre-v16 Header;
  // `k` is the lowercase keywords joined with "|" (a query never contains
  // "|", so `k.includes(q)` equals the old `keywords.some(kw.includes(q))`).
  const search = [];
  for (const cat of categories) {
    search.push({ t: 'category', n: cat.name, u: `/${cat.slug}`, k: [cat.name.toLowerCase(), (cat.tagline || '').toLowerCase()].join('|') });
    for (const pt of cat.productTypes || []) {
      search.push({ t: 'product', n: pt.name, c: cat.name, u: `/${cat.slug}/${pt.slug}`, k: [pt.name.toLowerCase(), cat.name.toLowerCase()].join('|') });
    }
  }
  for (const brand of idx.allBrandsUnified) {
    const catName = brand.categories?.[0]?.name || '';
    search.push({ t: 'brand', n: brand.name, c: catName, u: `/brand/${brand.simpleSlug}`, k: [brand.name.toLowerCase(), catName.toLowerCase(), (brand.country || '').toLowerCase()].join('|') });
  }

  const menus = {};
  for (const item of products.navigation.filter((i) => !i.isDropdown)) {
    const category = categories.find((cat) => `/${cat.slug}` === item.href);
    if (!category) continue;
    menus[item.href] = {
      category: { slug: category.slug, name: category.name, tagline: category.tagline || '' },
      productTypes: (category.productTypes || []).slice(0, 6).map((pt) => ({ slug: pt.slug, name: pt.name })),
      topBrands: idx.getTopBrandsForCategory(category.slug, 10).map((b) => ({ simpleSlug: b.simpleSlug, name: b.name })),
      brandCount: (category.brands || []).length,
    };
  }

  const brandCategorySlugs = {};
  for (const brand of idx.allBrandsUnified) {
    brandCategorySlugs[brand.simpleSlug] = [...new Set((brand.categories || []).map((c) => c.slug))];
  }

  const headerMenus = `${HEADER('Main-category dropdown menus, category list and brand counts (loaded on every page).')}
export const HEADER_CATEGORY_MENUS = ${JSON.stringify(menus, null, 1)};

export const CLIENT_CATEGORIES = ${JSON.stringify(categories.map((c) => ({ slug: c.slug, name: c.name })))};

export const CLIENT_BRAND_STATS = ${JSON.stringify(idx.getBrandStats())};
`;
  const headerSearchIndex = `${HEADER('Header search index (loaded lazily, on the first search keystroke).')}
export const HEADER_SEARCH_INDEX = ${JSON.stringify(search)};
`;
  const brandCategorySlugsFile = `${HEADER('Brand simple slug -> category slugs (contact form pre-ticking).')}
export const BRAND_CATEGORY_SLUGS = ${JSON.stringify(brandCategorySlugs)};
`;
  return {
    [path.join('src', 'data', 'headerMenus.js')]: headerMenus,
    [path.join('src', 'data', 'headerSearchIndex.js')]: headerSearchIndex,
    [path.join('src', 'data', 'brandCategorySlugs.js')]: brandCategorySlugsFile,
  };
}

// Returns [] when the files on disk match what the data would generate,
// otherwise the list of stale relative paths.
export async function staleClientIndexes(root = ROOT_DEFAULT) {
  const files = await buildClientIndexes(root);
  return Object.entries(files)
    .filter(([rel, content]) => {
      const abs = path.join(root, rel);
      return !fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== content;
    })
    .map(([rel]) => rel);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes('--check')) {
    const stale = await staleClientIndexes(ROOT_DEFAULT);
    if (stale.length) {
      console.error(`stale: ${stale.join(', ')} — run node scripts/build-client-indexes.mjs`);
      process.exit(1);
    }
    console.log('client indexes up to date');
  } else {
    const files = await buildClientIndexes(ROOT_DEFAULT);
    for (const [rel, content] of Object.entries(files)) {
      fs.writeFileSync(path.join(ROOT_DEFAULT, rel), content);
      console.log(`wrote ${rel} (${(content.length / 1024).toFixed(1)} KB)`);
    }
  }
}
